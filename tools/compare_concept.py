"""Side by side QA artifact; original reference pixels + actual Android view captures.
Run after ConceptScreenshotsTest. Requires matplotlib and Pillow (developer tooling only).
No screenshot is redrawn or generated by a model.
"""
from pathlib import Path
import os
root=Path(__file__).resolve().parents[1]
os.environ.setdefault("MPLCONFIGDIR",str(root/"app/build/mpl-cache"))
os.environ.setdefault("XDG_CACHE_HOME",str(root/"app/build/xdg-cache"))
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
from matplotlib.backends.backend_pdf import PdfPages
from PIL import Image

root=Path(__file__).resolve().parents[1]
release=root/'release/v3.2'
refs=release/'references'
shots=root/'app/build/screenshots'
out=release/'comparisons';out.mkdir(parents=True,exist_ok=True)
pairs=[('01_Home.png','concept-01-home-light.png','Home'),('02_Nuova_Spesa.png','concept-02-spesa-light.png','Nuova spesa'),('03_Categorie.png','concept-03-categorie-light.png','Categorie'),('04_Analisi.png','concept-04-analisi-light.png','Analisi'),('05_Rate.png','concept-05-rate-light.png','Rate'),('06_Conferma_Uscita.png','concept-06-conferma-light.png','Conferma di uscita')]
with PdfPages(out/'Confronti-V3.2.pdf') as pdf:
 for i,(ref,shot,title) in enumerate(pairs,1):
  fig,axes=plt.subplots(1,2,figsize=(8,10),facecolor='white')
  for ax,path,label in zip(axes,[refs/ref,shots/shot],['Concept originale','Implementazione Android']):
   with Image.open(path) as image:
    ax.imshow(image,interpolation='nearest' if label.startswith('Concept') else 'antialiased')
   ax.set_title(label,fontsize=13,pad=12);ax.set_axis_off()
  fig.suptitle(f'{i}. {title} — Posso spenderlo? V3.2',fontsize=16,y=.98)
  fig.text(.5,.02,'Riferimento a risoluzione limitata. Dati demo; proporzioni Android e accessibilità reali.\nLe catture provengono dai View Android (Robolectric Native Graphics), non da un telefono fisico.',ha='center',fontsize=8,color='#506D94')
  fig.tight_layout(rect=[0,.06,1,.95]);fig.savefig(out/f'{i:02d}-confronto.png',dpi=160);pdf.savefig(fig);plt.close(fig)
print('Creati 6 confronti PNG e un PDF, senza modificare i file originali.')
